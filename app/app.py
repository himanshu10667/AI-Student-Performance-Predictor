st.set_page_config(
    page_title="Student Performance Predictor",
    page_icon="🎓",
    layout="wide",
)

PROJECT_ROOT = Path(__file__).resolve().parent.parent
MODELS_DIR = PROJECT_ROOT / "models"
LOGISTIC_MODEL_PATH = MODELS_DIR / "logistic_regression.joblib"
PREPROCESSOR_PATH = MODELS_DIR / "preprocessor.joblib"

CATEGORICAL_FEATURES = [
    "gender",
    "race/ethnicity",
    "parental level of education",
    "lunch",
    "test preparation course",
]

PRACTICE_RECOMMENDATIONS = {
    "Low": (
        "Start with foundational practice. Review core concepts and work through "
        "guided, easier questions before progressing."
    ),
    "Medium": (
        "Practise core concepts with a mix of easy and moderate questions. "
        "Review mistakes and gradually increase difficulty."
    ),
    "High": (
        "Practise challenging application and multi-step questions, while using "
        "mixed practice to maintain existing skills."
    ),
}


@st.cache_resource
def load_model_and_preprocessor():
    """Load the fitted preprocessing object and model once per app process."""
    if not LOGISTIC_MODEL_PATH.exists():
        raise FileNotFoundError(
            f"Model file not found: {LOGISTIC_MODEL_PATH}\n"
            "Run Notebook 02 successfully and make sure the models/ folder is present."
        )
    if not PREPROCESSOR_PATH.exists():
        raise FileNotFoundError(
            f"Preprocessor file not found: {PREPROCESSOR_PATH}\n"
            "Run Notebook 02 successfully and make sure the models/ folder is present."
        )

    model = joblib.load(LOGISTIC_MODEL_PATH)
    preprocessor = joblib.load(PREPROCESSOR_PATH)

    try:
        encoder = preprocessor.named_transformers_["categorical"]
    except (AttributeError, KeyError) as exc:
        raise ValueError(
            "The saved preprocessor does not contain the expected 'categorical' encoder. "
            "Please confirm that it was generated by the current Notebook 02."
        ) from exc

    if len(CATEGORICAL_FEATURES) != len(encoder.categories_):
        raise ValueError(
            "The number of saved encoder feature categories does not match the app's "
            "expected input features. Check the preprocessor and Notebook 02."
        )

    allowed_categories = {
        feature: [str(value) for value in categories]
        for feature, categories in zip(CATEGORICAL_FEATURES, encoder.categories_)
    }
    return model, preprocessor, allowed_categories


def predict_mastery(student_profile, model, preprocessor, allowed_categories):
    """Predict a mastery category and return class probabilities."""
    missing = [feature for feature in CATEGORICAL_FEATURES if feature not in student_profile]
    if missing:
        raise ValueError(f"Missing required inputs: {', '.join(missing)}")

    for feature in CATEGORICAL_FEATURES:
        if student_profile[feature] not in allowed_categories[feature]:
            raise ValueError(
                f"Invalid value for {feature}: {student_profile[feature]!r}. "
                f"Allowed values: {allowed_categories[feature]}"
            )

    input_df = pd.DataFrame(
        [{feature: student_profile[feature] for feature in CATEGORICAL_FEATURES}],
        columns=CATEGORICAL_FEATURES,
    )
    transformed_input = preprocessor.transform(input_df)
    predicted_category = str(model.predict(transformed_input)[0])
    probability_values = model.predict_proba(transformed_input)[0]

    probabilities = pd.DataFrame(
        {
            "Mastery Level": [str(label) for label in model.classes_],
            "Probability": probability_values.astype(float),
        }
    ).sort_values("Probability", ascending=False, ignore_index=True)

    return predicted_category, probabilities


def recommend_after_exam(math_score, reading_score, writing_score):
    """Recommend subject(s) to review from exam scores; this is rule-based."""
    scores = {
        "Mathematics": float(math_score),
        "Reading": float(reading_score),
        "Writing": float(writing_score),
    }
    if any(not np.isfinite(score) or score < 0 or score > 100 for score in scores.values()):
        raise ValueError("Each exam score must be between 0 and 100.")

    lowest_score = min(scores.values())
    weakest_subjects = [subject for subject, score in scores.items() if score == lowest_score]

    if len(weakest_subjects) == 1:
        subjects_text = weakest_subjects[0]
        recommendation = (
            f"Prioritize {subjects_text}. Review foundational concepts, work through "
            "guided examples, and practise related questions."
        )
    else:
        subjects_text = ", ".join(weakest_subjects)
        recommendation = (
            f"Your lowest scores are tied in {subjects_text}. Review the core concepts "
            "in these subjects and practise related questions."
        )

    return scores, lowest_score, weakest_subjects, recommendation


